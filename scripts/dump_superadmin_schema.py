"""Dump the super-admin part of the con-backend GraphQL schema as SDL.

The super-admin API is served by the main schema (EmployeeManagement.schema)
at /graphql/. supreme_admin.schema.superadmin_sdl() keeps only the root fields
the super-admin Query/Mutation classes define (and every type they reach), so
the fixture stays small but is exactly what the served endpoint accepts.

Run from the con-backend checkout (needs the Django settings / database env):

    OUT=../CompanyRegistration-supremAdmin/tests/fixtures/superadmin-schema.graphql \
      python manage.py shell -c "exec(open('../CompanyRegistration-supremAdmin/scripts/dump_superadmin_schema.py').read())"

(On Windows cmd: `set OUT=...` first.) The backend test
SuperAdminSchemaSnapshotTest compares this file with the served schema when
this checkout sits next to con-backend. The supremAdmin tests validate every
gql document, and every mocked request, against that file.
"""
import os

from supreme_admin.schema import superadmin_sdl

HEADER = """# Super-admin GraphQL schema of con-backend (the part of /graphql/ that the
# super-admin Query/Mutation classes serve). Generated by
# scripts/dump_superadmin_schema.py -- regenerate it after a backend schema
# change; tests/schema/graphql-documents.spec.ts and the mocked GraphQL layers
# (tests/fixtures/graphql.fixture.ts, component-tests/fixtures/schema-mocks.tsx)
# validate every operation against it.

"""

try:
    sdl = superadmin_sdl()
except ValueError as error:
    raise SystemExit(str(error))
out = os.environ.get("OUT")
if out:
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(HEADER + sdl)
    print(f"Wrote {out} ({len(sdl)} bytes)")
else:
    print(sdl)
